#!/usr/bin/env bash
# Regenerate or check db/schema.sql, the reviewable snapshot of the schema the
# migrations build. It is GENERATED: never edit it by hand.
#
#   scripts/schema.sh --write   # rewrite db/schema.sql
#   scripts/schema.sh --check   # exit 1 if db/schema.sql is stale (CI)
#
# It starts a throwaway postgres:16-alpine container (no published port),
# applies every *.up.sql in order with ON_ERROR_STOP, and runs pg_dump
# --schema-only inside the same container. Needs only docker.
set -euo pipefail

mode="${1:-}"
if [[ "$mode" != "--write" && "$mode" != "--check" ]]; then
  echo "usage: $0 --write|--check" >&2
  exit 2
fi

here="$(cd "$(dirname "$0")/.." && pwd)"
out="$here/db/schema.sql"
name="dev-ops-schema-$$"

cleanup() { docker rm -f "$name" >/dev/null 2>&1 || true; }
trap cleanup EXIT

docker run -d --rm --name "$name" -e POSTGRES_PASSWORD=schema postgres:16-alpine >/dev/null
for i in $(seq 1 60); do
  # pg_isready on the unix socket can pass before the init restart; use a query.
  if docker exec "$name" psql -U postgres -tAc 'select 1' >/dev/null 2>&1; then
    break
  fi
  if [[ "$i" -eq 60 ]]; then
    echo "schema.sh: postgres did not start" >&2
    exit 2
  fi
  sleep 1
done
# The init entrypoint restarts the server once; wait for the final one.
sleep 2
until docker exec "$name" psql -U postgres -tAc 'select 1' >/dev/null 2>&1; do sleep 1; done

for f in "$here"/db/migrations/*.up.sql; do
  docker exec -i "$name" psql -q -v ON_ERROR_STOP=1 -U postgres -d postgres < "$f" >/dev/null
done

dump="$(docker exec "$name" pg_dump -U postgres -d postgres --schema-only --no-owner --no-privileges \
  | grep -v -E '^\\(un)?restrict ' \
  | grep -v -E '^-- Dumped (from|by) ')"
generated="-- GENERATED by scripts/schema.sh from db/migrations. Do not edit.
-- Regenerate: make schema. CI fails when this file is stale.
$dump"

if [[ "$mode" == "--write" ]]; then
  printf '%s\n' "$generated" > "$out"
  echo "wrote $out ($(wc -l < "$out") lines)"
  exit 0
fi

if ! diff -u "$out" <(printf '%s\n' "$generated"); then
  echo "schema.sh: db/schema.sql is stale. Run: make schema" >&2
  exit 1
fi
echo "db/schema.sql is current"
